// Flat list helper for search and lookups
export const ALL_NAV_ITEMS: NavItem[] = NAVIGATION_REGISTRY.flatMap(
  (cat) => cat.items,
);

// Get item by href
export function getNavItemByHref(href: string): NavItem | undefined {
  return ALL_NAV_ITEMS.find((item) => item.href === href);
}

// Get items by category
export function getNavCategory(categoryId: string): NavCategory | undefined {
  return NAVIGATION_REGISTRY.find((cat) => cat.id === categoryId);
}
